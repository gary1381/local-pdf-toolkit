#!/usr/bin/env python3
"""Browser check of the Redact tool through to the saved file.

Usage: python scripts/check_redact_tool.py BASE FIXTURES OUT [chromium|firefox|webkit]
FIXTURES is generated by engine/tests/make_fixtures.py. Requires Playwright.

Marks an area and words (typed, and found with a preset), applies the
redaction, saves, and checks the saved file: the marked content is gone,
the rest is there, an added text box became page content. Save with marks
not applied must ask first.

OPENPDF_CHECK_API: where the test's own helper requests go (finding text,
preparing and inspecting files); default BASE. Set it to a gateway to check
the browser version (web/dist), which has no server.
"""
import json
import os
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright


def main():
    base, fixtures, out = sys.argv[1].rstrip("/"), Path(sys.argv[2]), Path(sys.argv[3])
    api = os.environ.get("OPENPDF_CHECK_API", base).rstrip("/")
    browser_name = sys.argv[4] if len(sys.argv) > 4 else "chromium"
    out.mkdir(parents=True, exist_ok=True)
    results = []

    def check(name, ok, detail=""):
        results.append({"name": name, "passed": bool(ok), "detail": detail})
        print(f'{"PASS" if ok else "FAIL"} {name}{": " + str(detail) if detail else ""}', flush=True)

    with sync_playwright() as pw:
        browser = getattr(pw, browser_name).launch()
        ctx = browser.new_context(accept_downloads=True, viewport={"width": 1280, "height": 900})
        ctx.add_init_script("localStorage.setItem('openpdf_save_mode', 'download')")
        page = ctx.new_page()
        errors, dialogs = [], []
        page.on("pageerror", lambda e: errors.append(str(e)))

        def on_dialog(dialog):
            dialogs.append(dialog.message)
            dialog.accept()

        page.on("dialog", on_dialog)

        def find(blob, term, pages=""):
            r = ctx.request.post(api + "/v1/pdf/find-text", multipart={
                "file": {"name": "x.pdf", "mimeType": "application/pdf", "buffer": blob},
                "terms": json.dumps([term]), "pages": pages})
            assert r.ok, r.text()
            return r.json()["matches"]

        def page_point(page_num, x, y):
            shell = page.locator(f'.page-shell[data-page="{page_num}"]')
            # the page is at the top: scrolling a page taller than the window would move the point away
            scale = float(shell.get_attribute("data-scale"))
            box = shell.bounding_box()
            return box["x"] + x * scale, box["y"] + y * scale

        page.goto(base)
        source = fixtures / "contract.pdf"
        src = source.read_bytes()
        page.set_input_files("#fileInput", str(source))
        page.wait_for_function("() => activeDoc()?.documentId && activeDoc()?.pdfDoc")
        page.evaluate("() => activeDoc()._registerPromise")

        # a text box first: redaction must turn it into page content
        page.click('[data-mode="replace-text"]')
        page.mouse.click(*page_point(1, 300, 250))
        page.locator(".inline-text-editor").wait_for()
        page.keyboard.type("Reviewed by legal")
        page.keyboard.press("Enter")
        page.wait_for_function("() => activeDoc().placedTexts?.length === 1")

        page.click('[data-mode="redact"]')
        page.wait_for_selector('#propsPanel[data-panel="redact"]')
        check("Redact opens its panel", True)
        # an area: drag over the email address
        box = find(src, "john.smith@example.com", "1")[0]["boxes"][0]
        x0, y0 = page_point(1, box["x"] - 2, box["y"] - 2)
        x1, y1 = page_point(1, box["x"] + box["width"] + 2, box["y"] + box["height"] + 2)
        page.mouse.move(x0, y0)
        page.mouse.down()
        page.mouse.move(x1, y1, steps=5)
        page.mouse.up()
        page.wait_for_function("() => activeDoc().redaction?.areas.length === 1")
        check("dragging marks an area", page.locator(".redaction-mark:not(.redaction-term-mark)").count() == 1)
        # a typed word, and numbers found by the preset
        page.fill("#redactTermInput", "Acme Corp")
        page.click("#redactTermAdd")
        page.click('[data-preset="number"]')
        page.wait_for_function("() => activeDoc().redaction.terms.length >= 2")
        terms = page.evaluate("activeDoc().redaction.terms")
        check("words added (typed and found)", "Acme Corp" in terms and "123-45-6789" in terms, terms)
        page.wait_for_selector(".redaction-term-mark")
        check("marked words shown on the page", page.locator(".redaction-term-mark").count() >= 2)

        # Save before applying: asks; accepting applies first
        with page.expect_download() as download:
            page.keyboard.press("Control+s")
        saved = out / "redacted-contract.pdf"
        download.value.save_as(saved)
        page.wait_for_function("() => !activeDoc()._saving")
        check("save asks about marks not applied", any("not removed yet" in d for d in dialogs), dialogs)
        blob = saved.read_bytes()
        check("marked area removed", not find(blob, "john.smith@example.com"))
        check("marked words removed everywhere", not find(blob, "Acme Corp") and not find(blob, "123-45-6789"))
        check("account number found by the preset removed", not find(blob, "000123456789"))
        check("other text still there", find(blob, "Services Agreement", "1") or find(blob, "Services", "1"))
        check("text box became page content", find(blob, "Reviewed by legal", "1")
              and page.evaluate("activeDoc().placedTexts.length") == 0)
        page.wait_for_selector("#redactReport .redaction-report")
        check("report shown", "checked" in page.locator("#redactReport").inner_text().lower())
        check("no marks left after applying", page.locator(".redaction-mark").count() == 0)
        check("no uncaught JavaScript errors", not errors, errors)
        ctx.close()
        browser.close()
    (out / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=2))
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
