#!/usr/bin/env python3
"""Regression checks for exporting pending form edits.

Usage: python scripts/check_export_workflows.py BASE FIXTURES OUT [chromium|firefox|webkit]
FIXTURES is generated by engine/tests/make_fixtures.py. Requires Playwright.
Uses disposable browser state and fixture PDFs; never changes the input files.

OPENPDF_CHECK_API: where the test's own helper requests go (finding text,
preparing and inspecting files); default BASE. Set it to a gateway to check
the browser version (web/dist), which has no server.
"""
import json
import os
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright


def main():
    base, fixtures, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    api = os.environ.get("OPENPDF_CHECK_API", base).rstrip("/")
    browser_name = sys.argv[4] if len(sys.argv) > 4 else "chromium"
    out.mkdir(parents=True, exist_ok=True)
    results = []
    with sync_playwright() as pw:
        browser = getattr(pw, browser_name).launch()
        ctx = browser.new_context(accept_downloads=True, viewport={"width": 1280, "height": 820})
        ctx.add_init_script("localStorage.setItem('openpdf_save_mode', 'download')")
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(base)
        page.set_input_files("#fileInput", str(fixtures / "form.pdf"))
        page.wait_for_function("() => activeDoc()?.documentId && activeDoc()?.pdfDoc")
        page.click('[data-action="forms"]')
        field = page.locator('#propsBody input[data-form-index="0"]')

        def value(blob, password=None):
            upload = {"name": "audit.pdf", "mimeType": "application/pdf", "buffer": blob}
            if password:
                r = ctx.request.post(api + "/v1/pdf/unlock", multipart={"file": upload, "password": password})
                assert r.ok, r.text()
                upload["buffer"] = r.body()
            r = ctx.request.post(api + "/v1/pdf/form-fields", multipart={"file": upload})
            assert r.ok, r.text()
            return next(f.get("value", "") for f in r.json()["fields"] if f["name"] == "legal_name")

        def check(name, got, expected):
            ok = got == expected
            results.append({"name": name, "passed": ok, "actual": got, "expected": expected})
            print(f'{"PASS" if ok else "FAIL"} {name}: {got!r}', flush=True)

        field.fill("Ana Müller")
        page.evaluate('I18N.setLanguage("de")')
        check("live switch preserves unsaved form input", field.input_value(), "Ana Müller")
        # Capture the actual PDF sent to the iframe before its URL is revoked.
        page.evaluate("""() => {
            const create = URL.createObjectURL;
            URL.createObjectURL = blob => { window.auditPrintBlob = blob; return create(blob); };
        }""")
        page.keyboard.press("Control+p")
        page.wait_for_selector("#printDialog[open]")
        blob = bytes(page.evaluate("async () => Array.from(new Uint8Array(await window.auditPrintBlob.arrayBuffer()))"))
        (out / "printed-form.pdf").write_bytes(blob)
        check("print includes pending form value", value(blob), "Ana Müller")
        page.click("#printCloseBtn")
        page.evaluate('I18N.setLanguage("en")')
        field.fill("Zoë García")
        page.click(".file-menu-btn")
        page.click('[data-action="encrypt"]')
        page.fill('#toolDialog [data-field="password"]', "test-secret")
        page.fill('#toolDialog [data-field="confirm"]', "test-secret")
        with page.expect_download() as download:
            page.click("#toolSubmitBtn")
        encrypted = out / "encrypted-form.pdf"
        download.value.save_as(encrypted)
        check("encrypted copy includes pending form value", value(encrypted.read_bytes(), "test-secret"), "Zoë García")
        # Exporting must not mark the source as saved.
        check("export keeps source dirty", page.evaluate("activeDoc().dirty"), True)
        with page.expect_download() as download:
            page.keyboard.press("Control+s")
        saved = out / "saved-form.pdf"
        download.value.save_as(saved)
        page.wait_for_function("() => !activeDoc()._saving")
        check("ordinary save retains form value", value(saved.read_bytes()), "Zoë García")
        # An untouched signed document must remain byte-for-byte intact on Save.
        cert = ctx.request.post(api + "/v1/pdf/generate-cert", multipart={"name": "Audit Signer", "cert_password": "test-secret"})
        assert cert.ok, cert.text()
        signed = ctx.request.post(api + "/v1/pdf/digital-sign", multipart={
            "file": {"name": "form.pdf", "mimeType": "application/pdf", "buffer": saved.read_bytes()},
            "cert": {"name": "signer.p12", "mimeType": "application/x-pkcs12", "buffer": cert.body()},
            "cert_password": "test-secret", "visible": "false",
        })
        assert signed.ok, signed.text()
        original = signed.body()
        signed_path = out / "signed-form.pdf"
        signed_path.write_bytes(original)
        page.set_input_files("#fileInput", str(signed_path))
        page.wait_for_function("() => activeDoc()?.signatures?.length > 0")
        if not page.locator("#fillFormBtn").is_visible():
            page.click('[data-action="forms"]')
        page.wait_for_selector("#fillFormBtn")
        prompts, downloads = [], []
        accept = [False]
        page.on("dialog", lambda dialog: (prompts.append(dialog.message),
                                          dialog.accept() if accept[0] else dialog.dismiss()))
        page.on("download", lambda download: downloads.append(download))
        page.evaluate("() => actions.save()")
        resaved = out / "signed-form-resaved.pdf"
        if downloads:
            downloads[-1].save_as(resaved)
        check("unchanged signed form saves without an edit warning",
              not prompts and bool(downloads) and resaved.read_bytes() == original, True)
        # A change to the signed form (after the warning): appended after the signed bytes,
        # so the signature stays intact and shows as changed after signing.
        accept[0] = True
        page.click('[data-mode="replace-text"]')
        shell = page.locator('.page-shell[data-page="1"]')
        scale = float(shell.get_attribute("data-scale"))
        box = shell.bounding_box()
        page.mouse.click(box["x"] + 40 * scale, box["y"] + 300 * scale)
        page.locator(".inline-text-editor").wait_for()
        page.keyboard.type("Checked by legal")
        page.keyboard.press("Enter")
        downloads.clear()
        page.evaluate("() => actions.save()")
        page.wait_for_function("() => !activeDoc()._saving")
        page.wait_for_timeout(500)
        edited = out / "signed-form-edited.pdf"
        sigs = []
        if downloads:
            downloads[-1].save_as(edited)
            r = ctx.request.post(api + "/v1/pdf/verify-signatures", multipart={
                "file": {"name": "e.pdf", "mimeType": "application/pdf", "buffer": edited.read_bytes()}})
            sigs = r.json().get("signatures", [])
        check("a change to a signed form keeps the signature, changed after signing",
              bool(sigs) and sigs[0].get("status") != "invalid" and sigs[0].get("coversWholeFile") is False
              and edited.read_bytes().startswith(original), True)
        check("no uncaught JavaScript errors", errors, [])
        ctx.close()
        browser.close()
    (out / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=2))
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
