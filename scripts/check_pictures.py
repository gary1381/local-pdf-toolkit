#!/usr/bin/env python3
"""Regression checks for pictures: open pictures as a PDF, save a document's
pictures, export as Markdown, and the OCR dialog's picture option.

Usage: python scripts/check_pictures.py BASE FIXTURES OUT [chromium|firefox|webkit]
FIXTURES is generated by engine/tests/make_fixtures.py. Requires Playwright and
Pillow. Uses disposable browser state; never changes the input files.

OPENPDF_CHECK_API: where the test's own helper requests go (reading text);
default BASE. Set it to a gateway to check the browser version (web/dist).
OPENPDF_CHECK_STRUCTURE=1: the Markdown export must work (else it may say the
add-on is missing).
"""
import io
import json
import os
import sys
import zipfile
from pathlib import Path

from playwright.sync_api import sync_playwright


def make_pictures(out: Path) -> list[Path]:
    """Two photos of printed lines: one taken sideways (EXIF orientation 6), one PNG."""
    from PIL import Image, ImageDraw, ImageFont

    def page(lines):
        im = Image.new("RGB", (1240, 1754), "white")
        d = ImageDraw.Draw(im)
        try:
            font = ImageFont.truetype("DejaVuSans.ttf", 56)
        except OSError:
            font = ImageFont.load_default(size=56)
        for i, line in enumerate(lines):
            d.text((110, 140 + i * 110), line, fill="black", font=font)
        return im

    first = out / "01-receipt.jpg"
    exif = Image.Exif()
    exif[0x0112] = 6
    page(["Harbor Hardware", "Receipt 4471", "Total 38.20"]).rotate(90, expand=True).save(
        first, exif=exif.tobytes(), dpi=(150, 150), quality=90)
    second = out / "02-note.png"
    page(["Delivery note", "Order 9921"]).save(second, dpi=(150, 150))
    return [first, second]


def main():
    base, fixtures, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    api = os.environ.get("OPENPDF_CHECK_API", base).rstrip("/")
    need_structure = os.environ.get("OPENPDF_CHECK_STRUCTURE") == "1"
    browser_name = sys.argv[4] if len(sys.argv) > 4 else "chromium"
    out.mkdir(parents=True, exist_ok=True)
    pictures = make_pictures(out)
    results = []

    def check(name, ok, detail=""):
        results.append({"name": name, "passed": bool(ok), "detail": detail})
        print(f'{"PASS" if ok else "FAIL"} {name}{": " + str(detail) if detail else ""}', flush=True)

    with sync_playwright() as pw:
        browser = getattr(pw, browser_name).launch()
        ctx = browser.new_context(accept_downloads=True, viewport={"width": 1280, "height": 820})
        ctx.add_init_script("localStorage.setItem('openpdf_save_mode', 'download')")
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.goto(base)
        page.wait_for_function("() => typeof activeDoc === 'function'")

        def page_text(blob: bytes) -> list[str]:
            r = ctx.request.post(api + "/v1/pdf/page-text",
                                 multipart={"file": {"name": "x.pdf", "mimeType": "application/pdf", "buffer": blob}})
            assert r.ok, r.text()
            return [p["text"] for p in r.json()["pages"]]

        def doc_bytes() -> bytes:
            return bytes(page.evaluate(
                "async () => Array.from(new Uint8Array(await activeDoc().blob.arrayBuffer()))"))

        ocr_ready = page.evaluate("ocrInstalled()")

        # 1. two pictures from File → PDF from pictures: one page each, in name order, text recognised
        page.click(".file-menu-btn")
        with page.expect_file_chooser() as chooser:
            page.click('[data-action="fromImages"]')
        chooser.value.set_files([str(pictures[1]), str(pictures[0])])
        page.wait_for_selector("#toolDialog[open]")
        title = page.inner_text("#toolDialogTitle")
        check("pictures dialog names the count", "2" in title, title)
        ocr_box = page.locator('#toolDialog [data-field="ocr"]')
        check("OCR is on by default when installed", ocr_box.is_checked() == ocr_ready, f"installed={ocr_ready}")
        page.click("#toolSubmitBtn")
        page.wait_for_function("() => activeDoc()?.name === '01-receipt.pdf' && activeDoc()?.documentId",
                               timeout=180_000)
        check("PDF from pictures opens", page.evaluate("activeDoc().pageCount") == 2,
              page.evaluate("activeDoc().pageCount"))
        texts = page_text(doc_bytes())
        if ocr_ready:
            check("pictures' text recognised, in name order",
                  "Receipt 4471" in texts[0] and "Order 9921" in texts[1], [t[:60] for t in texts])
        # the sideways photo is shown upright: its page is taller than wide
        size = page.evaluate("""async () => { const p = await activeDoc().pdfDoc.getPage(1);
            const v = p.getViewport({ scale: 1 }); return [v.width, v.height]; }""")
        check("photo orientation kept", size[1] > size[0], size)

        # 2. a picture through Open (the ordinary file input) also becomes a PDF
        page.set_input_files("#fileInput", str(pictures[1]))
        page.wait_for_selector("#toolDialog[open]")
        page.locator('#toolDialog [data-field="ocr"]').set_checked(False)
        page.click("#toolSubmitBtn")
        page.wait_for_function("() => activeDoc()?.name === '02-note.pdf' && activeDoc()?.documentId",
                               timeout=120_000)
        check("Open accepts a picture (OCR off: no text)", page_text(doc_bytes())[0].strip() == "",
              page_text(doc_bytes())[0][:40])

        # 3. Save the pictures of a scan: a ZIP with the picture, its text and the manifest
        page.set_input_files("#fileInput", str(fixtures / "scan.pdf"))
        page.wait_for_function("() => activeDoc()?.name === 'scan.pdf' && activeDoc()?.documentId")
        page.click('[data-menu="toolsMenu"]')
        page.click('[data-action="exportImages"]')
        page.wait_for_selector("#toolDialog[open]")
        with page.expect_download(timeout=180_000) as download:
            page.click("#toolSubmitBtn")
        zipped = out / "scan-images.zip"
        download.value.save_as(zipped)
        with zipfile.ZipFile(zipped) as z:
            names = z.namelist()
            manifest = json.loads(z.read("manifest.json"))
        imgs = manifest.get("images", [])
        check("pictures ZIP", imgs and imgs[0]["file"] in names and imgs[0]["page"] == 1, names)
        if ocr_ready:
            check("picture text saved", "Riverside" in imgs[0].get("text", "")
                  and imgs[0]["file"].rsplit(".", 1)[0] + ".txt" in names, imgs[0].get("text", "")[:60])

        # a document without pictures says so instead of downloading an empty ZIP
        page.set_input_files("#fileInput", str(fixtures / "form.pdf"))
        page.wait_for_function("() => activeDoc()?.name === 'form.pdf' && activeDoc()?.documentId")
        page.click('[data-menu="toolsMenu"]')
        page.click('[data-action="exportImages"]')
        page.wait_for_selector("#toolDialog[open]")
        page.click("#toolSubmitBtn")
        page.wait_for_function("() => /No pictures/.test(document.getElementById('statusMessage')?.textContent || '')",
                               timeout=60_000)
        check("no pictures: says so", True)

        # 4. Export as Markdown (needs the structure add-on)
        page.set_input_files("#fileInput", str(fixtures / "report.pdf"))
        page.wait_for_function("() => activeDoc()?.name === 'report.pdf' && activeDoc()?.documentId")
        page.click('[data-menu="toolsMenu"]')
        page.click('[data-action="exportStructure"]')
        page.wait_for_function("""() => document.getElementById('toolDialog').open
            || /structure add-on/.test(document.getElementById('statusMessage')?.textContent || '')""")
        if page.evaluate("document.getElementById('toolDialog').open"):
            with page.expect_download(timeout=300_000) as download:
                page.click("#toolSubmitBtn")
            zipped = out / "report-markdown.zip"
            download.value.save_as(zipped)
            with zipfile.ZipFile(zipped) as z:
                md = z.read("report.md").decode()
            check("Markdown export", "## 1 Summary" in md and "<!-- page 1 of 2 -->" in md, md[:80])
        else:
            check("Markdown export says the add-on is missing", not need_structure,
                  page.inner_text("#statusMessage"))

        # 5. the OCR dialog offers the picture option, on by default
        page.set_input_files("#fileInput", str(fixtures / "contract.pdf"))
        page.wait_for_function("() => activeDoc()?.name === 'contract.pdf' && activeDoc()?.documentId")
        if ocr_ready:
            page.click('[data-menu="toolsMenu"]')
            page.click('[data-action="ocr"]')
            page.wait_for_selector("#toolDialog[open]")
            check("OCR dialog: pictures option on", page.locator('#toolDialog [data-field="pictures"]').is_checked())
            page.click("#toolCancelBtn")

        check("no page errors", not errors, errors[:3])
        browser.close()

    (out / "results.json").write_text(json.dumps(results, indent=1))
    failed = [r for r in results if not r["passed"]]
    print(f"{len(results) - len(failed)}/{len(results)} passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
