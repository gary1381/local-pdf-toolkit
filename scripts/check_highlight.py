#!/usr/bin/env python3
"""Browser check of the Highlight shapes and of the keys for selected text.

Usage: python scripts/check_highlight.py BASE FIXTURES OUT [chromium|firefox|webkit]
FIXTURES is generated by engine/tests/make_fixtures.py. Requires Playwright.

- Box: a dragged box becomes a highlight.
- Text: H again switches the shape; dragging over text highlights only its
  lines (one highlight with an area per line, saved in one request, one undo
  step), and the preview already looks like the saved highlight.
- Pen: a stroke drawn by hand becomes a highlighter stroke (Ink annotation);
  Erase highlight takes it where the area touches the stroke, not elsewhere.
- Selected text: H and Ctrl+H highlight it, W opens it in Edit text, R marks
  it for redaction.
- The shape chosen is remembered.
"""
import json
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright

ANNOTS = """async () => {
  const blob = await downloadDocumentBlob(activeDoc());
  const pdf = await pdfjsLib.getDocument({ data: await blob.arrayBuffer() }).promise;
  const page = await pdf.getPage(1);
  return (await page.getAnnotations()).map((a) => ({ type: a.subtype, rect: a.rect, quad: a.quadPoints }));
}"""


def main():
    base, fixtures, out = sys.argv[1].rstrip("/"), Path(sys.argv[2]), Path(sys.argv[3])
    browser_name = sys.argv[4] if len(sys.argv) > 4 else "chromium"
    out.mkdir(parents=True, exist_ok=True)
    results = []

    def check(name, ok, detail=""):
        results.append({"name": name, "passed": bool(ok), "detail": detail})
        print(f'{"PASS" if ok else "FAIL"} {name}{": " + str(detail) if detail else ""}', flush=True)

    with sync_playwright() as pw:
        browser = getattr(pw, browser_name).launch()
        ctx = browser.new_context(viewport={"width": 1280, "height": 900})
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))

        def open_pdf(path):
            page.set_input_files("#fileInput", str(path))
            page.wait_for_function(
                "name => activeDoc()?.name === name && activeDoc()?.documentId && activeDoc()?.pdfDoc", arg=path.name)
            page.evaluate("() => activeDoc()._registerPromise")
            page.wait_for_function("() => activeDoc()._editorSnapshot !== undefined")

        def point(x, y):
            shell = page.locator('.page-shell[data-page="1"]')
            scale = float(shell.get_attribute("data-scale"))
            box = shell.bounding_box()
            return box["x"] + x * scale, box["y"] + y * scale

        def drag(x0, y0, x1, y1):
            page.mouse.move(*point(x0, y0))
            page.mouse.down()
            page.mouse.move(*point((x0 + x1) / 2, (y0 + y1) / 2), steps=4)
            page.mouse.move(*point(x1, y1), steps=4)
            page.mouse.up()

        def settle():
            # the edit is queued after the mouse is released: let it start, then finish
            page.wait_for_timeout(600)
            page.wait_for_function("() => !activeDoc()._pendingMutations", timeout=20000)
            page.wait_for_timeout(300)

        def where():
            return page.evaluate("() => ({mode: state.editMode, shape: highlightShapeInfo().id, focus: document.activeElement?.tagName + '.' + (document.activeElement?.className || '')})")

        def annots():
            return page.evaluate(ANNOTS)

        def text_box(term):
            """The box of a word on page 1, from the page's own text."""
            return page.evaluate("""async (term) => {
                const shell = document.querySelector('.page-shell[data-page="1"]');
                const scale = Number(shell.dataset.scale);
                const it = (await pageTextItems(shell)).find((i) => i.str.includes(term));
                return it && { x: it.left / scale, base: it.base / scale, h: it.h / scale, right: it.right / scale };
            }""", term)

        page.goto(base)
        page.wait_for_function("() => typeof openFile === 'function' && typeof highlightShapeInfo === 'function'")
        page.evaluate("() => localStorage.removeItem('openpdf_highlight_shape')")
        open_pdf(fixtures / "contract.pdf")
        page.evaluate("() => document.activeElement?.blur()")
        # just after opening, the page is still being set up: press until the tool is on
        for _ in range(20):
            page.keyboard.press("h")
            page.wait_for_timeout(250)
            if page.evaluate("state.editMode") == "highlight":
                break
        page.wait_for_function("() => state.editMode === 'highlight'")
        check("H turns on Highlight with the Box shape", page.evaluate("highlightShapeInfo().id") == "box")
        # the page's drawing layer for the tool is in place
        page.wait_for_selector('.page-shell[data-page="1"] .selection-layer')
        page.wait_for_timeout(500)
        page.screenshot(path=str(out / "before-box.png"))

        # Box
        drag(400, 380, 470, 400)
        settle()
        a = annots()
        check("Box: a dragged box becomes a highlight", sum(1 for x in a if x["type"] == "Highlight") == 1,
              [a, page.evaluate("els.statusMessage.textContent")])

        # Text
        page.keyboard.press("h")
        check("H again switches to the Text shape", page.evaluate("highlightShapeInfo().id") == "text", where())
        pressed = page.locator('.highlight-shapes [aria-pressed="true"]').get_attribute("data-shape")
        check("the shape is shown as chosen in the tool's bar", pressed == "text", pressed)
        first = text_box("This agreement")
        second = text_box("Client SSN")
        before = len(annots())
        drag(first["x"] + 5, first["base"] - first["h"] * 0.6, first["x"] + 160, second["base"] + 1)
        settle()
        a = annots()
        new = [x for x in a[before:] if x["type"] == "Highlight"]
        # one highlight, one area (quad: 8 numbers) per line of text in the box
        def quads(r):
            q = r.get("quad")
            if isinstance(q, dict):
                q = [q[k] for k in sorted(q, key=int)]
            q = q or [r["rect"][0], r["rect"][3], r["rect"][2], r["rect"][3], r["rect"][0], r["rect"][1], r["rect"][2], r["rect"][1]]
            return [q[i:i + 8] for i in range(0, len(q), 8)]
        areas = [qd for r in new for qd in quads(r)]
        check("Text: one highlight with an area per line of text in the box", len(new) == 1 and len(areas) == 2, new)
        heights = [max(qd[1::2]) - min(qd[1::2]) for qd in areas]
        check("Text: each area as tall as its line, not the dragged box", all(h < first["h"] * 1.6 for h in heights), heights)
        page.keyboard.press("Control+z")
        settle()
        check("Text: one undo removes the lines highlighted together", len(annots()) == before, len(annots()))

        # Pen
        page.keyboard.press("h")
        check("H again switches to the Pen shape", page.evaluate("highlightShapeInfo().id") == "pen")
        check("the pen width can be chosen", page.locator(".highlight-pen-width").count() == 1)
        page.mouse.move(*point(100, 420))
        page.mouse.down()
        for i in range(1, 21):
            page.mouse.move(*point(100 + i * 6, 420 + (i % 4) * 2))
        page.mouse.up()
        settle()
        a = annots()
        inks = [x for x in a if x["type"] == "Ink"]
        check("Pen: the stroke becomes a highlighter stroke (Ink)", len(inks) == 1,
              [a, page.evaluate("els.statusMessage.textContent")])
        page.keyboard.press("e")
        page.wait_for_function("() => state.editMode === 'erase-highlight'")
        drag(150, 445, 190, 455)  # under the stroke, not on it
        settle()
        check("Erase: an area off the stroke leaves it", sum(1 for x in annots() if x["type"] == "Ink") == 1)
        drag(150, 414, 170, 430)  # across the stroke
        settle()
        check("Erase: an area across the stroke removes it", not any(x["type"] == "Ink" for x in annots()), annots())

        # keys on selected text
        page.keyboard.press("Escape")
        page.wait_for_function("() => state.editMode === 'select'")

        def select_text(term):
            page.evaluate("""(term) => {
                const span = [...document.querySelectorAll('.page-shell[data-page="1"] .textLayer span')]
                  .find((s) => s.textContent.includes(term));
                const node = span.firstChild;
                const at = node.textContent.indexOf(term);
                const range = document.createRange();
                range.setStart(node, at);
                range.setEnd(node, at + term.length);
                getSelection().removeAllRanges();
                getSelection().addRange(range);
            }""", term)
            page.wait_for_function("() => !document.getElementById('selectionToolbar').classList.contains('hidden')")

        page.wait_for_selector('.page-shell[data-page="1"] .textLayer span')
        count = sum(1 for x in annots() if x["type"] == "Highlight")
        select_text("Acme")
        page.keyboard.press("h")
        settle()
        after = sum(1 for x in annots() if x["type"] == "Highlight")
        check("selected text: H highlights it", after == count + 1, after)
        select_text("Client SSN")
        page.keyboard.press("Control+h")
        settle()
        check("selected text: Ctrl+H highlights it", sum(1 for x in annots() if x["type"] == "Highlight") == after + 1)
        select_text("agreement")
        page.keyboard.press("w")
        page.wait_for_selector(".inline-text-editor")
        check("selected text: W opens it in Edit text", "agreement" in (page.locator(".inline-text-editor").text_content() or ""))
        page.keyboard.press("Escape")
        page.keyboard.press("Escape")
        page.wait_for_function("() => state.editMode === 'select'")
        select_text("Acme")
        page.keyboard.press("r")
        page.wait_for_timeout(500)
        marked = page.evaluate("() => redactionOf(activeDoc()).areas.length")
        check("selected text: R marks it for redaction", marked == 1 and page.evaluate("state.editMode") == "redact", marked)

        # remembered
        page.reload()
        page.wait_for_function("() => typeof highlightShapeInfo === 'function'")
        check("the shape chosen is remembered", page.evaluate("highlightShapeInfo().id") == "pen")

        check("no uncaught JavaScript errors", not errors, errors)
        ctx.close()
        browser.close()
    (out / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=2))
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
