#!/usr/bin/env python3
"""Browser check of "Edit text" and "Add text" through to the saved file.

Usage: python scripts/check_edit_text.py BASE FIXTURES OUT [chromium|firefox|webkit]
FIXTURES is generated by engine/tests/make_fixtures.py. Requires Playwright.

Edit text: clicking a line of the page opens it for editing, prefilled; the
saved file no longer contains the old text but the new one (any reader can
see it). Add text: the new text is in the saved file. Reopened in OpenPDF,
the boxes are editable again and the drawn copy is hidden (not shown twice).

OPENPDF_CHECK_API: where the test's own helper requests go (finding text,
preparing and inspecting files); default BASE. Set it to a gateway to check
the browser version (web/dist), which has no server.
"""
import json
import os
import sys
from pathlib import Path

from playwright.sync_api import sync_playwright


def main():
    base, fixtures, out = sys.argv[1].rstrip("/"), Path(sys.argv[2]), Path(sys.argv[3])
    api = os.environ.get("OPENPDF_CHECK_API", base).rstrip("/")
    browser_name = sys.argv[4] if len(sys.argv) > 4 else "chromium"
    out.mkdir(parents=True, exist_ok=True)
    results = []

    def check(name, ok, detail=""):
        results.append({"name": name, "passed": bool(ok), "detail": detail})
        print(f'{"PASS" if ok else "FAIL"} {name}{": " + str(detail) if detail else ""}', flush=True)

    with sync_playwright() as pw:
        browser = getattr(pw, browser_name).launch()
        ctx = browser.new_context(accept_downloads=True, viewport={"width": 1280, "height": 900})
        ctx.add_init_script("localStorage.setItem('openpdf_save_mode', 'download')")
        page = ctx.new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))

        def find(blob, term, pages=""):
            r = ctx.request.post(api + "/v1/pdf/find-text", multipart={
                "file": {"name": "x.pdf", "mimeType": "application/pdf", "buffer": blob},
                "terms": json.dumps([term]), "pages": pages})
            assert r.ok, r.text()
            return r.json()["matches"]

        def open_pdf(path):
            page.set_input_files("#fileInput", str(path))
            page.wait_for_function(
                "name => activeDoc()?.name === name && activeDoc()?.documentId && activeDoc()?.pdfDoc", arg=path.name)
            page.evaluate("() => activeDoc()._registerPromise")
            page.wait_for_function("() => activeDoc()._editorSnapshot !== undefined")

        def click_page_point(page_num, x, y):
            shell = page.locator(f'.page-shell[data-page="{page_num}"]')
            # the page is at the top: scrolling a page taller than the window would move the point away
            scale = float(shell.get_attribute("data-scale"))
            box = shell.bounding_box()
            page.mouse.click(box["x"] + x * scale, box["y"] + y * scale)

        def save(name):
            with page.expect_download() as download:
                page.keyboard.press("Control+s")
            path = out / name
            download.value.save_as(path)
            page.wait_for_function("() => !activeDoc()._saving")
            return path

        page.goto(base)
        source = fixtures / "contract.pdf"
        src = source.read_bytes()
        target = find(src, "123-45-6789", "1")[0]["boxes"][0]
        open_pdf(source)

        # Edit text: click the number, the line opens prefilled; change the number
        page.click('[data-mode="cover-text"]')
        click_page_point(1, target["x"] + target["width"] / 2, target["y"] + target["height"] / 2)
        editor = page.locator(".inline-text-editor")
        editor.wait_for()
        before = editor.text_content()
        check("clicking a line opens it prefilled", "123-45-6789" in before and "Client SSN" in before, before)
        page.keyboard.press("Control+a")
        page.keyboard.type(before.replace("123-45-6789", "XXX-XX-0000"))
        page.keyboard.press("Enter")
        page.wait_for_function("() => activeDoc().placedTexts?.length === 1")
        check("the edit is a box over the line", page.evaluate("activeDoc().placedTexts[0].kind") == "cover")
        check("it keeps the look of the line (font, size, colour on save)",
              page.evaluate("!!(activeDoc().placedTexts[0].matchStyle && activeDoc().placedTexts[0].origin)"))

        # Add text: click an empty spot and type
        page.click('[data-mode="replace-text"]')
        click_page_point(1, 300, 250)
        editor.wait_for()
        page.keyboard.type("Added line 42")
        page.keyboard.press("Enter")
        page.wait_for_function("() => activeDoc().placedTexts?.length === 2")

        saved = save("edited-contract.pdf")
        blob = saved.read_bytes()
        check("old text gone from the saved file", not find(blob, "123-45-6789", "1"))
        check("new text in the saved file", find(blob, "XXX-XX-0000", "1"))
        check("rest of the line kept", find(blob, "john.smith@example.com", "1"))
        check("added text in the saved file", find(blob, "Added line 42", "1"))
        check("other page untouched", find(blob, "123-45-6789", "2"))
        # the lines around it are separate lines (ended by hand), not a paragraph to rewrap
        r = ctx.request.post(api + "/v1/pdf/text-layout", multipart={
            "file": {"name": "x.pdf", "mimeType": "application/pdf", "buffer": blob}, "pages": "1"})
        phrases = [p["text"] for p in r.json()["pages"][0]["phrases"]]
        check("neighbouring lines kept as they were",
              any(p.startswith("The Client will pay") for p in phrases)
              and any(p.rstrip().endswith("example.com") for p in phrases), phrases[:6])

        # reopen: editable again, drawn copy hidden
        open_pdf(saved)
        try:
            page.wait_for_function("() => activeDoc().placedTexts?.length === 2", timeout=15000)
        except Exception:  # noqa: BLE001 - reported below
            pass
        check("boxes editable again after reopening", page.evaluate("activeDoc().placedTexts?.length") == 2,
              page.evaluate("activeDoc().placedTexts?.length"))
        run = page.evaluate("""async () => {
            const shell = document.querySelector('.page-shell[data-page="1"]');
            const scale = Number(shell.dataset.scale);
            const r = await textRunAt(shell, 305 * scale, 258 * scale);
            return r && r.text;
        }""")
        check("drawn copy of an added box is not taken for page text", not run or "Added line" not in run, run)
        hidden = page.evaluate("async () => !!(await editsLayerHidden(activeDoc().pdfDoc))")
        check("drawn copy hidden in OpenPDF (not shown twice)", hidden)

        # deleting the boxes and saving removes the drawn copy too
        page.evaluate("() => { activeDoc().placedTexts = []; activeDoc().placementsDirty = true; activeDoc().dirty = true; }")
        blob2 = save("cleared-contract.pdf").read_bytes()
        check("no drawn text once the boxes are deleted",
              not find(blob2, "Added line 42") and not find(blob2, "XXX-XX-0000"))
        check("edited text stays removed", not find(blob2, "123-45-6789", "1"))

        check("no uncaught JavaScript errors", not errors, errors)
        ctx.close()
        browser.close()
    (out / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=2))
    return 0 if all(r["passed"] for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
